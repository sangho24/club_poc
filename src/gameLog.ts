// 문자중계 원문 - 1회초부터 9회초까지
//
// ── 왜 game.ts 가 아니라 여기인가 ────────────────────────────
// game.ts 의 PLATE_SEQUENCE 는 **엔진이 먹는 상황 데이터**다. 타석마다 아웃카운트·주자·
// 볼카운트를 다 들고 있어야 liveEngine 이 승리확률과 레버리지를 다시 계산할 수 있다.
// 그래서 한 타석을 적는 값이 열 줄이 넘고, 8회말~9회말 아홉 타석만으로도 파일이 무겁다.
//
// 반면 이 파일은 **읽히기만 하는 중계 원문**이다. 엔진이 건드리지 않고 화면이 이닝별
// 아코디언으로 펼쳐 보여 주기만 한다. 계산에 쓰이지 않으니 상황 필드가 필요 없고,
// 필요한 것은 '누가' '무엇을 했나' 둘뿐이다.
//
// 둘을 한 파일에 섞으면 두 가지가 나빠진다. 첫째로 엔진용 데이터에 중계용 필드가 붙어
// 무엇이 계산에 쓰이는 값인지가 흐려진다. 둘째로 중계를 1회까지 늘리는 순간 PLATE_SEQUENCE
// 형식으로는 40타석 넘는 상황 데이터를 손으로 적어야 한다 - 그중 한 줄만 틀려도 엔진이
// 엉뚱한 확률을 뱉는다. 계산에 쓰이지 않는 데이터는 계산에 쓰이는 데이터와 떨어뜨려 둔다.
//
// 8회말·9회말은 여기 없다. 그 구간은 PLATE_SEQUENCE 몫이고, 화면은 두 소스를 이어 붙여
// 하나의 중계로 그린다. 같은 타석을 두 곳에 적으면 반드시 어긋난다.
//
// ── 지켜야 하는 수치 제약 ───────────────────────────────────
// **화면의 라인스코어가 이 데이터에서 나온다**(src/liveFeed.ts 의 lineScoreAt).
// 표를 따로 적어 두지 않으므로 여기가 틀리면 표도 같이 틀린다. 라인스코어와 문자중계가
// 같은 화면에 있는데 2회 득점이 서로 다르면 앱이 자기 말을 뒤집는다.
//   · 이닝 득점  LG(초) 0·1·0·0·2·0·1·0·0 = 4 / 한화(말) 0·0·2·0·0·1·0 = 3
//   · 안타       LG 9개(9회초까지) / 한화 5개(7회말까지). 8회말·9회말 안타는 PLATE_SEQUENCE 가 센다
//   · 실책       한화 수비 1개(4회초 3루수) / LG 수비 0개
//   · 각 하프이닝은 정확히 3아웃. 병살타 한 행이 2아웃이다
//   · 타순은 이닝을 넘어 이어진다. 한화는 1회말~7회말 29타석이고 29번째가 페라자(2번)라
//     PLATE_SEQUENCE 8회말 첫 타자 문현빈(3번)으로 그대로 넘어간다. **이 29는 고정이다**
//   · 마운드  한화 류현진(1~6회) → 이형범(7회) → 김범준(8~9회) / LG 임찬규 완투 중
//
// ⚠ 시연용 샘플이다. 실서비스에서는 KBO 문자중계 피드가 이 자리에 들어온다.
// 그때는 위 제약을 사람이 맞추는 것이 아니라 피드가 이미 맞춰서 준다.

/** 문자중계 한 행 */
export interface LogRow {
  /** 타석에 선 선수 이름. 투수 교체 같은 상황 행은 kind:'sub' 로 두고 이름 칸을 비운다 */
  name: string;
  /** 결과 한 마디. '중전 안타' '3구 헛스윙 삼진' 처럼 짧게 */
  text: string;
  /** 이 타석에서 난 점수 */
  runs?: number;
  /** 타석이 아닌 행(투수 교체 등) - 타순·아웃 계산에서 빠진다 */
  kind?: 'sub';
}

/** 한 하프이닝 */
export interface HalfInning {
  inning: number;
  half: 'top' | 'bottom';
  /** 이 이닝 득점 */
  runs: number;
  /** 이 이닝 안타 */
  hits: number;
  /** 이 이닝에 **수비 팀**이 범한 실책 */
  errors: number;
  rows: LogRow[];
}

