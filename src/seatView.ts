// 좌석 시야 - 구단 공식 VR 딥링크
//
// ── 왜 별도 파일인가 ────────────────────────────────────────
// gameday.ts 는 '오늘 구장에 가는 일'(예매·주차·게이트·반입)을 담는다. 여기 있는 것은
// **좌석 등급 ↔ 실제 구역 ↔ 외부 파노라마** 라는 다른 축의 매핑이고, 구역 판독 근거를
// 항목마다 주석으로 남겨야 해서 분량이 붙는다. SEAT_GRADES 옆에 그대로 쌓으면
// 예매 데이터가 판독 메모에 파묻힌다.
//
// ── 이 기능이 정직해야 하는 지점 ────────────────────────────
// 앱의 좌석 등급 5개는 PoC 용으로 단순화한 것이고 구단 실제 등급 체계는 더 잘게 나뉜다.
// 그래서 이 표는 '이 등급 = 이 구역'이 아니라 **대표 구역 한 곳**을 고른 것이다.
// 화면에 구역 번호를 함께 적는 이유가 여기 있다 - 팬이 지금 무엇을 보고 있는지
// 알아야 "내 자리도 이렇게 보이겠구나"를 스스로 조정할 수 있다. 구역을 숨긴 채
// "이 좌석에서 이렇게 보입니다"라고 말하면 그건 추정치를 확정처럼 파는 것이다
// (docs/design-decisions.md 12번 - 추정치를 실시간인 척 보여주면 팬이 화면 전체를 안 믿는다).
import type { SeatGradeId } from './gameday';

/**
 * 구단 공식 VR - krpano 1.22.3, 파노라마 185개.
 *
 * 구장 시야를 우리가 다시 찍지 않는다. 구단이 이미 전 구역을 찍어 공개해 두었고,
 * 지도를 네이버·카카오로 넘기는 것과 같은 판단이다 - **넘기되 잘 넘긴다.**
 */
const VR_BASE = 'https://www.hanwhaeagles.co.kr/resources/vr/index.html';

/**
 * 좌석 등급이 가리키는 대표 구역 한 곳.
 */
export interface SeatView {
  /**
   * 화면에 적는 구역 표기.
   *
   * 번호만 적으면 처음 오는 팬에게는 암호이고, 위치만 적으면 좌석배치도와 대조할 수
   * 없다. 둘을 붙여 `번호 · 위치` 로 적는다.
   */
  zoneLabel: string;
  /**
   * krpano 씬 이름.
   *
   * 규칙은 `scene_` + 구역ID 소문자다(`100B` → `scene_100b`, `107_2` → `scene_107_2`).
   * 그런데도 **규칙에서 파생하지 않고 문자열을 그대로 적는다** - 파생시키면 아직
   * 열어 보지 않은 구역까지 링크가 만들어지고, 없는 씬을 넘기면 VR 이 조용히
   * 기본 시점으로 열려 팬은 다른 자리를 보면서 자기 자리라고 믿는다.
   * 아래 값은 전부 실제로 열어 확인한 것만 있다.
   */
  scene: string;
}

/**
 * 등급 → 대표 구역.
 *
 * ⚠ `Record<SeatGradeId, ...>` 라서 **등급을 하나 추가하면 여기서 컴파일이 멈춘다.**
 * 매핑을 잊고 지나가면 그 등급만 시야 링크가 없는 채로 배포되는데, 화면에서는
 * 그냥 한 줄이 비어 보일 뿐이라 아무도 눈치채지 못한다. 타입으로 막는다.
 *
 * 판독 근거(한화이글스 공식 좌석배치도): 1루 = HOME(한화), 3루 = AWAY.
 * 100번대 1층 · 200번대 2층 · 300번대 3층 · 400번대 4층 · 500번대 외야 스탠드.
 */
export const SEAT_VIEWS: Record<SeatGradeId, SeatView> = {
  // 100A(1루쪽 앞줄 포수후면석) / 100B(정중앙 중앙지정석) / 100C(3루쪽 중앙탁자석) 중
  // 100B 를 골랐다 - 등급 note 가 '백네트 뒤'라 정중앙이 그 말에 맞는 유일한 구역이다.
  s1: { zoneLabel: '100B · 정중앙 1층', scene: 'scene_100b' },

  // 등급명은 '1루 내야지정석'(109~112 · 101~104)인데 **note 를 따라 카스존(105~108)으로 갔다.**
  // note 가 '홈 응원석 · 육성 응원 구역'이라고 못 박고 있고, 대전에서 육성 응원이
  // 벌어지는 곳은 내야지정석이 아니라 홈 응원단석인 카스존이다. 등급명은 PoC 가
  // 단순화하며 뭉갠 이름이고 note 가 팬이 실제로 사는 자리를 가리킨다.
  s2: { zoneLabel: '105~108 · 1루 응원석', scene: 'scene_107_2' },

  // 3루 내야지정석A(113~121) 의 가운데. 122~124(B) 는 외야 쪽으로 밀려 있어
  // '3루 내야'의 대표라기엔 끝자락이다.
  s3: { zoneLabel: '113~121 · 3루 1층', scene: 'scene_117_2' },

  // 외야지정석은 501~503(좌중간·3루쪽) 과 504~508(우중간~우익·1루쪽) 로 갈린다.
  // note 가 '가족 단위 · 응원 소음 적음'이라 원정 응원석과 붙은 3루쪽보다
  // 홈 1루쪽인 504~508 이 맞는다.
  s4: { zoneLabel: '504~508 · 우중간 외야', scene: 'scene_505_1' },

  // 500 밤켈존 - 좌익 잔디 스탠드. 잔디석은 이 한 구역뿐이라 고를 것이 없다.
  s5: { zoneLabel: '500 · 좌익 잔디', scene: 'scene_500_1' },
};

/**
 * 딥링크 URL.
 *
 * `?startscene=` 으로 씬을 직접 지정하면 그 구역에서 열린다(실측 확인).
 *
 * ⚠ **인트로 오버레이는 우리가 없앨 수 없다.** VR 이 열리면 "360° VR 관람 TIP" 이
 * 먼저 뜨고 '경기장 관람하기'를 한 번 눌러야 파노라마가 나온다. 구단 페이지의
 * 동작이라 링크로 건너뛸 방법이 없으므로, 링크 옆 캡션이 **미리 말해 준다** -
 * 예상하지 못한 화면이 뜨면 팬은 링크가 잘못됐다고 생각하고 되돌아 나간다.
 */
export function seatViewUrl(scene: string): string {
  return `${VR_BASE}?startscene=${encodeURIComponent(scene)}`;
}

/**
 * 좌석 카드 아래 캡션.
 *
 * 두 가지를 한 번에 말한다 - ① 보이는 것은 등급 전체가 아니라 대표 구역 한 곳이다
 * ② 열리면 안내 화면이 먼저 뜬다. 행마다 반복하면 다섯 줄짜리 경고문이 되어
 * 정작 가격·잔여가 안 읽히므로 카드에 한 번만 둔다.
 */
export const SEAT_VIEW_CAPTION =
  '구역 번호는 등급을 대표하는 한 곳입니다. 같은 등급 안에서도 자리마다 시야가 다릅니다. ' +
  '구단 공식 VR 이 열리며, 첫 화면의 ‘경기장 관람하기’를 누르면 보입니다.';
