export interface StatExplain {
  /** 지표 키 - sabermetrics 의 계산 함수와 짝 */
  key: string;
  /** 화면 표기명 */
  label: string;
  /** 한 줄 요약 - 값 옆에 바로 붙는다 */
  short: string;
  what: string;
  why: string;
  read: string;
  trap: string;
  /** 같이 봐야 뜻이 완성되는 지표 */
  seeAlso: string[];
  /**
   * 좋은 값의 대략 범위 - 게이지 눈금에 쓴다.
   *
   * `low` 는 언제나 **나쁜 쪽 끝**, `high` 가 좋은 쪽 끝이다. 낮을수록 좋은 지표(FIP·삼진율)는
   * low > high 로 뒤집어 적는다 - gaugePosition 이 이 방향을 그대로 정규화한다.
   *
   * `midText` 는 게이지가 '평균 N' 을 적을 때 쓴다. 비율 지표는 타일에 % 로 뜨는데
   * 눈금만 0.19 로 적히면 같은 값이 화면에서 두 얼굴을 갖는다.
   */
  scale?: {
    low: number;
    mid: number;
    high: number;
    better: 'high' | 'low';
    midText?: string;
  };
}

