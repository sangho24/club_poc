/**
 * 지식 수준에 맞춰 해설을 골라 준다.
 *
 * 같은 데이터로 다른 문장을 낸다. 입문자에게 trap 을 먼저 던지면 지표를 배우기도 전에
 * 불신부터 갖게 되고, 기록을 파는 팬에게 what 부터 읽히면 앱을 유치하다고 느낀다.
 */
export function explainFor(key: string, level: KnowledgeLevel): string[] {
  const g = GLOSSARY[key];
  if (!g) return [];
  if (level === 'rookie') return [g.what, g.read];
  if (level === 'fan') return [g.short, g.read, g.trap];
  return [g.why, g.read, g.trap]; // nerd: 정의는 이미 안다. 왜 만들어졌는지와 함정만
}

/** 지표 값을 게이지 위치(0~1)로 - 방향(better)이 low 면 뒤집는다 */
export function gaugePosition(key: string, value: number): number | null {
  const s = GLOSSARY[key]?.scale;
  if (!s) return null;
  const span = s.high - s.low;
  if (span === 0) return null;
  const raw = (value - s.low) / span;
  return Math.min(1, Math.max(0, raw));
}
